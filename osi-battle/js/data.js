/* Schaden ist EINHEITLICH. Dadurch tötet exakt die gewählte Zahl richtiger
   Antworten die Hydra: Gesamt-HP = Fragen x Schaden, und jede Kopf-HP ist
   ein Vielfaches des Schadens, sodass kein Treffer verpufft.
   Kritische Treffer sind reine Optik und verändern den Schaden nicht. */
const HIT_DAMAGE = 30;
/* Zuschlag eines kritischen Treffers. Er wird beim nächsten Treffer auf
   denselben Kopf wieder abgezogen, damit die Gesamtzahl gleich bleibt. */
const CRIT_BONUS = 15;

/** Verteilt N Treffer möglichst gleichmäßig auf die sieben Köpfe. */
function verteileTreffer(n) {
  const basis = Math.floor(n / 7), rest = n % 7;
  return [...Array(7)].map((_, i) => basis + (i < rest ? 1 : 0));
}

